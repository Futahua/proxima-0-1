// Build the existing AYG/Papers composition renderer into Proxima's own script origin.
// Source ownership stays in AYG; these generated assets contain no separate layout engine.
import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const project=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const ayg=path.resolve(process.argv[2]||path.join(project,'../AYGCrossDeviceSource'));
const papers=path.resolve(process.argv[3]||path.join(project,'../PapersCrossDeviceSource'));
const require=createRequire(path.join(papers,'package.json'));
const {build}=require('esbuild');
await build({entryPoints:[path.join(ayg,'public/app/coordinated-window-slices.js')],bundle:true,format:'esm',platform:'browser',target:'es2022',outfile:path.join(project,'public/blob-pane-coordinator.js'),banner:{js:'// Generated by tools/build-blob-layout.mjs from AYG shared pane sources.'}});
const css=await Promise.all(['file-capability.css','workspace-pane-layout.css'].map(name=>readFile(path.join(ayg,'public/styles',name),'utf8')));
await writeFile(path.join(project,'public/blob-pane-native.css'),'/* Generated from AYG shared pane styles by tools/build-blob-layout.mjs. */\n'+css.join('\n'));
